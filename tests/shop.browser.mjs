import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

export async function browserChecks(base) {
  const browser = await chromium.launch({ channel: process.env.TEST_BROWSER || 'chrome', headless: true });
  try {
    await mkdir('test-results', { recursive: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    page.setDefaultTimeout(45000);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(base + '/admin');
    await page.getByLabel('Adresse e-mail').fill(process.env.ADMIN_EMAIL);
    await page.getByLabel('Mot de passe').fill(process.env.ADMIN_PASSWORD);
    await page.getByRole('button', { name: 'Se connecter', exact: true }).click();
    await page.getByRole('heading', { name: 'Vos commandes', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Articles & stock', exact: true }).click();
    await page.getByRole('button', { name: 'Ajouter un article', exact: true }).click();
    await page.getByLabel('Nom de l’article').fill('Article navigateur');
    await page.getByLabel('Description', { exact: true }).fill('Article pour tester le parcours client.');
    await page.getByLabel('Prix (FCFA)', { exact: true }).fill('3500');
    await page.getByLabel('Stock disponible', { exact: true }).fill('4');
    const chooserPromise = page.waitForEvent('filechooser');
    await page.getByRole('button', { name: 'Choisir une photo dans mes fichiers', exact: true }).click();
    await (await chooserPromise).setFiles('public/logo-artech.jpeg');
    await page.waitForFunction(() => document.querySelector('input[name="image"]')?.value.startsWith('/api/images/'));
    const uploadedPhoto = await page.locator('input[name="image"]').inputValue();
    await page.screenshot({ path: 'test-results/photo-article.png', fullPage: true });
    await page.getByRole('button', { name: 'Enregistrer l’article', exact: true }).click();
    await page.getByRole('cell').filter({ hasText: 'Article navigateur' }).waitFor();
    await page.screenshot({ path: 'test-results/admin-desktop.png', fullPage: true });
    await page.goto(base + '/boutique');
    await page.getByRole('button', { name: 'Ajouter Article navigateur au panier', exact: true }).waitFor();
    const photo = page.locator('.store-product').filter({ hasText: 'Article navigateur' }).locator('img');
    assert.equal(await photo.getAttribute('src'), uploadedPhoto);
    await photo.evaluate(image => image.decode());
    assert.ok(await photo.evaluate(image => image.naturalWidth > 0));
    await page.screenshot({ path: 'test-results/boutique-desktop.png', fullPage: true });
    await page.getByRole('button', { name: 'Ajouter Article navigateur au panier', exact: true }).click();
    await page.reload();
    await page.getByRole('button', { name: 'Panier 1', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Ajouter Article navigateur au panier', exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'No mobile horizontal overflow');
    await page.screenshot({ path: 'test-results/boutique-mobile.png', fullPage: true });
    await page.getByRole('button', { name: 'Panier 1', exact: true }).click();
    await page.getByLabel('Nom complet', { exact: true }).fill('Client navigateur');
    await page.getByLabel('Téléphone', { exact: true }).fill('+22791111111');
    await page.screenshot({ path: 'test-results/panier-mobile.png', fullPage: true });
    await page.getByRole('button', { name: 'Confirmer ma commande', exact: true }).click();
    await page.waitForURL(/\/commande\/[a-f0-9]{64}$/);
    await page.getByRole('heading', { name: 'Merci pour votre confiance.', exact: true }).waitFor();
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('link', { name: 'Télécharger le reçu PDF', exact: true }).click();
    const download = await downloadPromise;
    assert.ok(download.suggestedFilename().endsWith('.pdf'));
    await page.getByLabel('Référence de votre transaction').fill('BROWSER-TX-456');
    await page.getByRole('button', { name: 'J’ai effectué le transfert', exact: true }).click();
    await page.getByText('Paiement à vérifier', { exact: true }).waitFor();
    await page.screenshot({ path: 'test-results/commande-mobile.png', fullPage: true });
    await page.goto(base + '/admin');
    await page.getByRole('heading', { name: 'Vos commandes', exact: true }).waitFor();
    const order = page.locator('.admin-order').filter({ hasText: 'Client navigateur' });
    await order.getByRole('button', { name: 'Valider le paiement', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Confirmer', exact: true }).click();
    await order.getByText('Payé', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'No admin mobile overflow');
    await page.screenshot({ path: 'test-results/admin-mobile.png', fullPage: true });
    await page.goto(base + '/boutique');
    await page.getByRole('button', { name: 'Ajouter Article navigateur au panier', exact: true }).click();
    await page.getByRole('button', { name: 'Panier 1', exact: true }).click();
    await page.getByLabel('Nom complet', { exact: true }).fill('Client retrait');
    await page.getByLabel('Téléphone', { exact: true }).fill('+22792222222');
    await page.getByLabel('Paiement en boutique', { exact: true }).check();
    await page.getByRole('button', { name: 'Confirmer ma commande', exact: true }).click();
    await page.waitForURL(/\/commande\/[a-f0-9]{64}$/);
    await page.getByRole('heading', { name: 'Payer à la boutique avec votre reçu', exact: true }).waitFor();
    await page.screenshot({ path: 'test-results/retrait-recu-mobile.png', fullPage: true });
    await page.goto(base + '/admin');
    const pickupOrder = page.locator('.admin-order').filter({ hasText: 'Client retrait' });
    await pickupOrder.getByRole('button', { name: 'Encaisser en boutique', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Confirmer', exact: true }).click();
    await pickupOrder.getByText('Payé', { exact: true }).waitFor();
    await page.goto(base + '/boutique');
    await page.getByRole('button', { name: 'Ajouter Article navigateur au panier', exact: true }).click();
    await page.getByRole('button', { name: 'Panier 1', exact: true }).click();
    await page.getByLabel('Nom complet', { exact: true }).fill('Client livraison');
    await page.getByLabel('Téléphone', { exact: true }).fill('+22793333333');
    await page.getByLabel('Livraison', { exact: true }).check();
    await page.getByLabel('Quartier, adresse et repères de livraison').fill('Quartier test, rue 12, porte bleue');
    await page.getByRole('button', { name: 'Confirmer ma commande', exact: true }).click();
    await page.waitForURL(/\/commande\/[a-f0-9]{64}$/);
    const deliveryUrl = page.url();
    await page.getByRole('heading', { name: 'Frais de livraison à confirmer', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Référence de votre transaction').count(), 0);
    await page.goto(base + '/admin');
    const deliveryOrder = page.locator('.admin-order').filter({ hasText: 'Client livraison' });
    await deliveryOrder.getByRole('spinbutton').fill('1500');
    await deliveryOrder.getByRole('button', { name: 'Confirmer les frais', exact: true }).click();
    await page.getByText('Commande mise à jour.', { exact: true }).waitFor();
    await page.goto(deliveryUrl);
    await page.getByLabel('Référence de votre transaction').waitFor();
    assert.match((await page.locator('.payment-account').innerText()).replace(/\s/g, ''), /5000FCFA/);
    await page.screenshot({ path: 'test-results/livraison-mobile.png', fullPage: true });
    assert.deepEqual(errors, [], 'No client runtime errors');
    console.log('PASS Browser: admin product creation, persistent cart, mobile checkout, PDF download, manual payment, admin approval, responsive layouts');
    console.log('PASS Browser: pickup receipt and in-store collection; delivery address and admin-confirmed delivery fee');
  } finally { await browser.close(); }
}
